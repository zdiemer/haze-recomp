"""Check the guest stack-access transform and the SDK's inline stack accessors.

The transform cases run the real patch module on small lifted-code samples. The
accessor cases compile ppu_stack_access.h against stub original accessors that
record each call, so every case can tell the inline path from the fallback.
"""
from __future__ import annotations

import argparse
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'scripts'))
from patches.patch_stack_access import patch  # noqa: E402

HEADER = '/* Auto-generated by ppu_lifter.py -- do not edit by hand. */\n#include "ppu_recomp.h"\n'
LIFTED = HEADER + '''#include <stdio.h>
void f(ppu_context* ctx) {
        vm_write64(ctx->gpr[1] + -0x80, ctx->gpr[1]); ctx->gpr[1] += -0x80;
        vm_write64(ctx->gpr[1] + 0x70, ctx->gpr[31]);
        vm_write32(ctx->gpr[1] + 0xD0, ctx->gpr[26]);
        vm_write16(ctx->gpr[1] + 8, ctx->gpr[3]);
        vm_write8(ctx->gpr[1] + 0x9, ctx->gpr[4]);
        ctx->gpr[0] = vm_read64(ctx->gpr[1] + 0x90);
        ctx->gpr[3] = vm_read32(ctx->gpr[1] + 0x70);
        ctx->gpr[5] = vm_read16(ctx->gpr[1] + -2);
        ctx->gpr[6] = vm_read8(ctx->gpr[1] + 0x10);
        ctx->gpr[7] = vm_read64(ctx->gpr[11] + 0x10);
        ctx->gpr[8] = vm_read32(ctx->gpr[1] + ctx->gpr[9]);
        vm_write32(ctx->gpr[12] + 0x4, ctx->gpr[1]);
        ctx->gpr[9] = vm_read64(ctx->gpr[10]);
        ctx->gpr[10] = my_vm_read64(ctx->gpr[1] + 0x8);
}
'''
EXPECTED_BODY = '''void f(ppu_context* ctx) {
        vm_stack_write64(ctx->gpr[1] + -0x80, ctx->gpr[1]); ctx->gpr[1] += -0x80;
        vm_stack_write64(ctx->gpr[1] + 0x70, ctx->gpr[31]);
        vm_stack_write32(ctx->gpr[1] + 0xD0, ctx->gpr[26]);
        vm_stack_write16(ctx->gpr[1] + 8, ctx->gpr[3]);
        vm_stack_write8(ctx->gpr[1] + 0x9, ctx->gpr[4]);
        ctx->gpr[0] = vm_stack_read64(ctx->gpr[1] + 0x90);
        ctx->gpr[3] = vm_stack_read32(ctx->gpr[1] + 0x70);
        ctx->gpr[5] = vm_stack_read16(ctx->gpr[1] + -2);
        ctx->gpr[6] = vm_stack_read8(ctx->gpr[1] + 0x10);
        ctx->gpr[7] = vm_read64(ctx->gpr[11] + 0x10);
        ctx->gpr[8] = vm_read32(ctx->gpr[1] + ctx->gpr[9]);
        vm_write32(ctx->gpr[12] + 0x4, ctx->gpr[1]);
        ctx->gpr[9] = vm_read64(ctx->gpr[10]);
        ctx->gpr[10] = my_vm_read64(ctx->gpr[1] + 0x8);
}
'''

FIXTURE = r'''
#include <cassert>
#include <cstdint>
#include <cstdio>
#include <cstring>
static uint8_t storage[0x30000];
extern "C" { uint8_t* vm_base = storage; unsigned char vm_inline_page[0x10000]; }
static int full_calls;
static uint64_t full_address;
#define FULL_READ(T, n) static T vm_read##n(uint64_t a) { ++full_calls; full_address = a; return (T)0x5A; }
#define FULL_WRITE(T, n) static void vm_write##n(uint64_t a, T) { ++full_calls; full_address = a; }
FULL_READ(uint8_t, 8) FULL_READ(uint16_t, 16) FULL_READ(uint32_t, 32) FULL_READ(uint64_t, 64)
FULL_WRITE(uint8_t, 8) FULL_WRITE(uint16_t, 16) FULL_WRITE(uint32_t, 32) FULL_WRITE(uint64_t, 64)
#include "ppu_stack_access.h"

static bool reads_inline(uint64_t a) {
    const uint32_t ea = (uint32_t)a;
    memcpy(storage + ea, "\x01\x23\x45\x67\x89\xAB\xCD\xEF", 8);
    full_calls = 0;
    const bool b8 = vm_stack_read8(a) == 0x01, b16 = vm_stack_read16(a) == 0x0123;
    const bool b32 = vm_stack_read32(a) == 0x01234567u;
    const bool b64 = vm_stack_read64(a) == 0x0123456789ABCDEFull;
    const bool fast = b8 && b16 && b32 && b64;
    assert(fast ? full_calls == 0 : full_calls == 4 && !b8 && !b16 && !b32 && !b64);
    if (!fast) assert(full_address == a);
    return fast;
}
static bool writes_inline(uint64_t a) {
    const uint32_t ea = (uint32_t)a;
    memset(storage + ea - 1, 0xA5, 10);
    full_calls = 0;
    vm_stack_write64(a, 0x0123456789ABCDEFull);
    const bool fast = full_calls == 0;
    if (fast) {
        assert(!memcmp(storage + ea, "\x01\x23\x45\x67\x89\xAB\xCD\xEF", 8));
        vm_stack_write32(a, 0x10203040u); vm_stack_write16(a + 4, 0x5060); vm_stack_write8(a + 6, 0x70);
        assert(!memcmp(storage + ea, "\x10\x20\x30\x40\x50\x60\x70\xEF", 8));
        assert(storage[ea - 1] == 0xA5 && storage[ea + 8] == 0xA5 && full_calls == 0);
    } else {
        assert(full_address == a && storage[ea] == 0xA5);
        vm_stack_write32(a, 0); vm_stack_write16(a, 0); vm_stack_write8(a, 0);
        assert(full_calls == 4 && storage[ea] == 0xA5);
    }
    return fast;
}

int main() {
    // Every access calls the original accessor until the loader marks a page.
    assert(!reads_inline(0x10010) && !writes_inline(0x10010));
    vm_inline_page[1] = 1;
    assert(reads_inline(0x10010) && writes_inline(0x10010));
    assert(reads_inline(0x1FFF0) && writes_inline(0x1FFF0));
    // Unaligned and the page's other neighbours.
    assert(reads_inline(0x10003) && writes_inline(0x10005));
    assert(!reads_inline(0x20010) && !writes_inline(0x20010));
    // The page comes from the low 32 bits, as in the original accessors, and
    // the fallback still receives the untruncated address.
    assert(reads_inline(0x100010010ull) && writes_inline(0x100010010ull));
    assert(!reads_inline(0x100020010ull));
    // A page taken off the inline path (an SPU reservation) falls back.
    vm_inline_page[1] = 0;
    assert(!reads_inline(0x10010) && !writes_inline(0x10010));
    puts("PASS");
}
'''


def check_transform() -> int:
    out = patch(LIFTED)
    expected = HEADER + '#include "ppu_stack_access.h"\n#include <stdio.h>\n' + EXPECTED_BODY
    assert out == expected, out
    # A module with no stack accesses is unchanged and gains no include.
    plain = HEADER + 'void g(ppu_context* ctx) { ctx->gpr[3] = vm_read32(ctx->gpr[4] + 8); }\n'
    assert patch(plain) == plain
    for broken, reason in ((LIFTED.replace('#include "ppu_recomp.h"\n', ''), 'ppu_recomp.h'),
                           (out, 'vm_stack_')):
        try:
            patch(broken)
        except ValueError as error:
            assert reason in str(error), error
        else:
            raise AssertionError(f'patch accepted a module without {reason}')
    return 4


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--compiler', required=True)
    parser.add_argument('--sdk', type=Path, default=ROOT / 'external/ps3recomp')
    parser.add_argument('--output-dir', type=Path, required=True)
    args = parser.parse_args()
    checks = check_transform()
    args.output_dir.mkdir(parents=True, exist_ok=True)
    fixture = args.output_dir / 'stack_access.cpp'
    fixture.write_text(FIXTURE, encoding='utf-8')
    exe = args.output_dir / 'stack_access.exe'
    subprocess.run([args.compiler, '/nologo', '/O2', '/std:c++17', '/EHsc', '/W4',
                    f'/I{args.sdk / "runtime/ppu"}', f'/Fo{exe.with_suffix(".obj")}', f'/Fe{exe}',
                    str(fixture)], check=True)
    run = subprocess.run([str(exe)], capture_output=True, text=True, timeout=10)
    assert run.returncode == 0 and 'PASS' in run.stdout, (run.stdout, run.stderr)
    print(f'PASS {checks} stack-access transform cases and the inline accessor fixture')


if __name__ == '__main__':
    main()
